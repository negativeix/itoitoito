// Generates supabase/migrations/0004_themes.sql from src/data/themes.ts.
// Run: npm run gen:themes
import { writeFileSync } from 'node:fs'
import { THEMES } from '../src/data/themes.ts'

const q = (s) => `'${String(s).replaceAll("'", "''")}'`
const rows = THEMES.map((t) => `  (${q(t.id)}, ${q(t.category)}, ${q(t.title)}, ${q(t.low)}, ${q(t.high)})`)

const sql = `-- GENERATED by scripts/gen-themes-sql.mjs from src/data/themes.ts — do not edit by hand.
insert into themes (id, category, title, low, high) values
${rows.join(',\n')}
on conflict (id) do update set category = excluded.category, title = excluded.title, low = excluded.low, high = excluded.high;

delete from themes where id not in (${THEMES.map((t) => q(t.id)).join(', ')});
`

writeFileSync(new URL('../supabase/migrations/0004_themes.sql', import.meta.url), sql)
console.log(`wrote ${THEMES.length} themes`)
